def corpus(split, size):
    rows = DEV if split == "dev" else HELDOUT
    documents = [(f"target-{index}", statement, True) for index, (statement, _, _) in enumerate(rows)]
    queries = []
    for index, (_, positive, negative) in enumerate(rows):
        direction = ("vi-en", "en-vi", "en-en", "vi-vi", "vi-unaccented-en")[index % 5]
        queries.append(dict(id=f"{split}-hit-{index}", query=positive, expected=f"target-{index}", bucket=direction))
        queries.append(dict(id=f"{split}-empty-{index}", query=negative, expected=None,
                            bucket="stale" if index % 5 == 0 else "absent"))
        if index % 5 == 0:
            documents.append((f"revoked-{index}", negative, False))
    for index in range(size - len(rows)):
        documents.append((f"filler-{index}", DISTRACTORS[index % len(DISTRACTORS)].format(index + 1), True))
    assert len({doc_id for doc_id, _, active in documents if active}) == size
    assert len(queries) == 60
    return documents, queries
